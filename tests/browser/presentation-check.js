(async () => {
  const assert = (ok, message) => { if (!ok) throw new Error(message); };
  const pause = () => new Promise(resolve => setTimeout(resolve, 250));
  const graph = document.querySelector('graph-component');
  assert(graph, 'ready-made graph is present');
  const link = document.querySelector('article.note a[data-note-preview]');
  assert(link, 'inline wiki link has a preview');
  const button = link.nextElementSibling;
  assert(button?.matches('button.note-preview-trigger'), 'touch preview has a separate button');
  const popup = document.querySelector('#inline-note-preview');
  assert(popup, 'preview popup exists');
  link.dispatchEvent(new PointerEvent('pointerenter', {pointerType:'mouse'}));
  await pause();
  assert(popup.matches(':popover-open'), 'hover opens preview');
  assert(popup.querySelector('.katex'), 'math renders in preview');
  const rect = popup.getBoundingClientRect();
  assert(rect.left >= 0 && rect.right <= innerWidth && rect.bottom <= innerHeight, 'preview fits viewport');
  popup.dispatchEvent(new KeyboardEvent('keydown', {key:'Escape', bubbles:true}));
  assert(!popup.matches(':popover-open'), 'Escape closes preview');
  link.focus();
  await pause();
  assert(popup.matches(':popover-open'), 'keyboard focus opens preview');
  popup.querySelector('[data-close-preview]').click();
  assert(!popup.matches(':popover-open'), 'close button closes preview');
  button.click();
  assert(popup.matches(':popover-open'), 'touch button opens preview');
  assert(document.activeElement === popup.querySelector('[data-close-preview]'), 'explicit opening moves focus to popup');
  const ids = [...document.querySelectorAll('[id]')].map(element=>element.id);
  assert(new Set(ids).size === ids.length, 'preview creates no duplicate IDs');
  popup.querySelector('[data-close-preview]').click();
  assert(document.activeElement === button, 'closing restores button focus');
  assert(link.getAttribute('href').startsWith('/notes/'), 'original link still navigates');
  assert(graph.querySelector('canvas'), 'graph rendered a canvas');
  assert(graph.simulator.nodes.length >= 3, 'graph contains the sample notes, not an empty canvas');
  const controls = [...graph.querySelectorAll('.slsg-graph-action-button')];
  assert(controls.length === 5 && controls.every(control=>control.getAttribute('aria-label')), 'all graph controls have accessible names');
  const depth = JSON.parse(graph.dataset.config).depth;
  controls[1].focus();
  controls[1].click();
  await pause();
  assert(JSON.parse(graph.dataset.config).depth !== depth, 'ready-made depth control works');
  assert(document.activeElement?.dataset.graphAction === 'depth', 'regenerating depth control retains keyboard focus');
  graph.querySelector('[data-graph-action="settings"]').click();
  await pause();
  assert(document.querySelector('.slsg-popup-menu input[type="range"]'), 'ready-made settings panel opens');
  const slider = document.querySelector('.slsg-popup-menu input[type="range"]');
  slider.value = '500';
  slider.dispatchEvent(new Event('input',{bubbles:true}));
  await pause();
  assert(JSON.parse(graph.dataset.config).repelForce === 500, 'settings change graph physics');
  document.body.click();
  const sitemap = graph.dataset.sitemap;
  graph.dataset.sitemap = JSON.stringify({...JSON.parse(sitemap), 'notes/disconnected-test':{title:'نوت مستقل آزمایشی',exists:true,external:false,links:[],backlinks:[],tags:[]}});
  await pause();
  assert(!graph.simulator.nodes.some(node=>node.id==='notes/disconnected-test'), 'local graph excludes disconnected notes');
  while (JSON.parse(graph.dataset.config).depth !== 5) {
    graph.querySelector('[data-graph-action="depth"]').click();
    await pause();
  }
  assert(graph.simulator.nodes.some(node=>node.id==='notes/disconnected-test'), 'global graph includes disconnected notes');
  graph.dataset.sitemap = sitemap;
  await pause();
  graph.querySelector('[data-graph-action="fullscreen"]').click();
  await pause();
  assert(graph.querySelector('.slsg-is-fullscreen'), 'fullscreen opens');
  graph.graphContainer.dispatchEvent(new KeyboardEvent('keyup',{key:'Escape',bubbles:true}));
  await pause();
  assert(!graph.querySelector('.slsg-is-fullscreen'), 'Escape exits fullscreen');
  return {preview:'hover/focus/touch/Escape/math/viewport/IDs',graph:'nodes/local/global/labels/keyboard/depth/settings/fullscreen',width:innerWidth};
})()
